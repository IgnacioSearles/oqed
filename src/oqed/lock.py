"""`oqed.lock`: verified winners for `oqed-cc` to apply at build time.

A reviewable TOML file, meant to be committed next to the code it speeds up.
Each entry names a C function, the signature the code was proven for, the
`-march` whose instructions it uses, and the assembly. `oqed-cc` re-proves
every entry against the function as it is in the source being compiled, so a
stale entry falls back to the C rather than miscompiling.
"""

from __future__ import annotations

import json
import tomllib
from pathlib import Path

from pydantic import BaseModel

from .targets import IntType

LOCK_NAME = "oqed.lock"
VERSION = 1


class LockEntry(BaseModel):
    function: str  # C function name in the project
    args: list[IntType]
    ret: IntType
    march: str  # the code only uses instructions this -march allows
    asm: str  # Intel-syntax function body ending in ret
    # "proven": oqed-cc proves it again per build. "tested" (oqed optimize --unsafe):
    # the proof was inconclusive; oqed-cc substitutes it when differential testing passes.
    status: str
    speedup: float  # inlined latency vs the better of clang/gcc -O3 when found
    benchmark: str  # benchmarks/<name> the search ran on
    run: str
    candidate: str
    # "project": judged by building the project and running its test command
    # (the function touches memory); oqed-cc then only checks `slice_sha`, the
    # hash of the function and the declarations it uses, against the source.
    oracle: str = "harness"
    slice_sha: str | None = None


def _toml_str(s: str) -> str:
    return json.dumps(s)  # a JSON string is a valid TOML basic string


def dumps(entries: list[LockEntry]) -> str:
    out = [
        "# oqed.lock: assembly that oqed-cc substitutes for C functions at build time.",
        "# Generated by `oqed optimize`. Review it like code. oqed-cc proves each entry",
        "# against the function in your source, compiled with your flags, on every",
        "# build, and keeps the C when the proof fails or a loop stops vectorizing.",
        '# Entries with status "tested" (oqed optimize --unsafe) were never proven:',
        "# oqed-cc applies them when the proof is inconclusive and testing passes.",
        f"version = {VERSION}",
    ]
    for e in sorted(entries, key=lambda e: (e.function, e.march)):
        out += [
            "",
            "[[entry]]",
            f"function = {_toml_str(e.function)}",
            f"args = [{', '.join(_toml_str(a) for a in e.args)}]",
            f"ret = {_toml_str(e.ret)}",
            f"march = {_toml_str(e.march)}",
            f"status = {_toml_str(e.status)}",
            f"speedup = {e.speedup}",
            f"benchmark = {_toml_str(e.benchmark)}",
            f"run = {_toml_str(e.run)}",
            f"candidate = {_toml_str(e.candidate)}",
            *([f"oracle = {_toml_str(e.oracle)}"] if e.oracle != "harness" else []),
            *([f"slice_sha = {_toml_str(e.slice_sha)}"] if e.slice_sha else []),
            'asm = """',
            e.asm.rstrip("\n").replace("\\", "\\\\").replace('"""', '\\"""'),
            '"""',
        ]
    return "\n".join(out) + "\n"


def load(path: Path) -> list[LockEntry]:
    data = tomllib.loads(path.read_text())
    if data.get("version") != VERSION:
        raise ValueError(f"{path}: unsupported lock version {data.get('version')!r}")
    return [LockEntry(**e) for e in data.get("entry", [])]


def merge(old: list[LockEntry], new: list[LockEntry]) -> list[LockEntry]:
    """New entries replace old ones for the same function and -march."""
    keys = {(e.function, e.march) for e in new}
    return [e for e in old if (e.function, e.march) not in keys] + new


def find(start: Path) -> Path | None:
    """The nearest `oqed.lock` in `start` or a parent directory."""
    for d in [start, *start.parents]:
        if (d / LOCK_NAME).is_file():
            return d / LOCK_NAME
    return None
