"""Generate cover.pb-c.h / cover.pb-c.c: a message that exercises every part
of protobuf-c's wire format, for the `--check` test oqed uses as its oracle.

`Cover` has every scalar type as required, optional, proto3 (no label) and
repeated (packed and unpacked) fields, strings, bytes, a oneof, a nested
message and repeated nested messages, with field numbers up to the maximum
(536870911) so every tag size occurs. `CoverLite` describes the same struct
with a third of the scalar fields left out: unpacking with it turns those into
unknown fields, which packing writes back. `CoverOpt` (no required fields) is
the type of the required field `must`, which may be NULL: it packs as empty.

The descriptors are written in the form protoc-c generates (protoc-c isn't
installed here). Also generated: `cover__random()`, which fills a message
with random values biased to edge cases (0, -1, minimum and maximum, powers
of two), and a bump allocator for it.

    python3 gen_cover.py    # rewrites cover.pb-c.h and cover.pb-c.c
"""

from pathlib import Path

# protobuf type -> (C type, random-value expression)
SCALARS = {
    "int32": ("int32_t", "(int32_t) rv_bits(32)"),
    "sint32": ("int32_t", "(int32_t) rv_bits(32)"),
    "sfixed32": ("int32_t", "(int32_t) rv_bits(32)"),
    "int64": ("int64_t", "(int64_t) rv_bits(64)"),
    "sint64": ("int64_t", "(int64_t) rv_bits(64)"),
    "sfixed64": ("int64_t", "(int64_t) rv_bits(64)"),
    "uint32": ("uint32_t", "(uint32_t) rv_bits(32)"),
    "fixed32": ("uint32_t", "(uint32_t) rv_bits(32)"),
    "uint64": ("uint64_t", "rv_bits(64)"),
    "fixed64": ("uint64_t", "rv_bits(64)"),
    "float": ("float", "rv_float()"),
    "double": ("double", "rv_double()"),
    "bool": ("protobuf_c_boolean", "(protobuf_c_boolean) (rnd() & 1)"),
    "enum": ("Cover__Color", "rv_color()"),
    "string": ("char *", "rv_string()"),
    "bytes": ("ProtobufCBinaryData", "rv_bytes()"),
}
PACKABLE = [t for t in SCALARS if t not in ("string", "bytes")]
ONEOF = [("pick_int", "int32"), ("pick_sint", "sint64"), ("pick_str", "string"), ("pick_bytes", "bytes")]
# Field numbers for the last few fields, so 1- to 5-byte tags all occur.
LARGE_IDS = [2047, 2048, 262143, 262144, 100000000, 536870911]


class Field:
    def __init__(self, name, ptype, label, packed=False, oneof=False):
        self.name, self.ptype, self.label, self.packed, self.oneof = name, ptype, label, packed, oneof
        self.id = 0

    @property
    def ctype(self):
        return "struct Cover *" if self.ptype == "message" else SCALARS[self.ptype][0]


def fields() -> list[Field]:
    out = []
    for t in SCALARS:
        out.append(Field(f"r_{t}", t, "REQUIRED"))
        out.append(Field(f"o_{t}", t, "OPTIONAL"))
        out.append(Field(f"n_{t}", t, "NONE"))
        out.append(Field(f"x_{t}", t, "REPEATED"))
        if t in PACKABLE:
            out.append(Field(f"p_{t}", t, "REPEATED", packed=True))
    out += [Field(name, t, "OPTIONAL", oneof=True) for name, t in ONEOF]
    out.append(Field("child", "message", "OPTIONAL"))
    out.append(Field("must", "message", "REQUIRED"))  # may be NULL: packs as empty
    out.append(Field("kids", "message", "REPEATED"))
    small = len(out) - len(LARGE_IDS)
    for i, f in enumerate(out):
        f.id = i + 1 if i < small else LARGE_IDS[i - small]
    return out


def in_lite(i: int, f: Field) -> bool:
    return f.oneof or f.ptype == "message" or i % 3 != 1


def header(fs: list[Field]) -> str:
    members = []
    for f in fs:
        if f.oneof:
            continue
        if f.label == "OPTIONAL" and f.ptype not in ("string", "message"):
            members.append(f"\tprotobuf_c_boolean has_{f.name};")
        if f.label == "REPEATED":
            members.append(f"\tsize_t n_{f.name};")
            members.append(f"\t{f.ctype} *{f.name};" if not f.ctype.endswith("*") else f"\t{f.ctype}*{f.name};")
        else:
            members.append(f"\t{f.ctype} {f.name};" if not f.ctype.endswith("*") else f"\t{f.ctype}{f.name};")
    members.append("\tCover__PickCase pick_case;")
    members.append("\tunion {")
    for f in fs:
        if f.oneof:
            members.append(f"\t\t{f.ctype} {f.name};" if not f.ctype.endswith("*") else f"\t\t{f.ctype}{f.name};")
    members.append("\t};")
    cases = "\n".join(f"\tCOVER__PICK_{f.name.upper()} = {f.id}," for f in fs if f.oneof)
    body = "\n".join(members)
    return f"""/* Generated by gen_cover.py in the form protoc-c generates. */
#ifndef COVER_PB_C_H
#define COVER_PB_C_H

#include "protobuf-c.h"

typedef enum {{
	COVER__COLOR__RED = 0,
	COVER__COLOR__GREEN = 1,
	COVER__COLOR__BLUE = 5,
	COVER__COLOR__NEGATIVE = -3,
}} Cover__Color;

typedef enum {{
	COVER__PICK__NOT_SET = 0,
{cases}
}} Cover__PickCase;

typedef struct Cover {{
	ProtobufCMessage base;
{body}
}} Cover;

extern const ProtobufCMessageDescriptor cover__descriptor;
extern const ProtobufCMessageDescriptor cover_lite__descriptor;
extern const ProtobufCMessageDescriptor cover_opt__descriptor;
extern const ProtobufCEnumDescriptor cover__color__descriptor;

void cover__init(Cover *message);
void cover_lite__init(Cover *message);
void cover_opt__init(Cover *message);

/* Random message (depth limits nesting), allocated from a bump arena that
 * cover__arena_reset() frees in one go. */
void cover__random(Cover *message, int depth);
void cover__arena_reset(void);
void cover__seed(uint64_t seed);

#endif
"""


def descriptor_table(fs: list[Field], prefix: str, msg_desc: str) -> str:
    rows = []
    for f in fs:
        flags = []
        if f.packed:
            flags.append("PROTOBUF_C_FIELD_FLAG_PACKED")
        if f.oneof:
            flags.append("PROTOBUF_C_FIELD_FLAG_ONEOF")
        if f.oneof:
            quant = "offsetof(Cover, pick_case)"
        elif f.label == "REPEATED":
            quant = f"offsetof(Cover, n_{f.name})"
        elif f.label == "OPTIONAL" and f.ptype not in ("string", "message"):
            quant = f"offsetof(Cover, has_{f.name})"
        else:
            quant = "0"
        sub = "&cover_opt__descriptor" if f.name == "must" else f"&{msg_desc}"
        desc = {"message": sub, "enum": "&cover__color__descriptor"}.get(f.ptype, "NULL")
        rows.append(
            f'\t{{ "{f.name}", {f.id}, PROTOBUF_C_LABEL_{f.label}, PROTOBUF_C_TYPE_{f.ptype.upper()}, {quant},\n'
            f"\t  offsetof(Cover, {f.name}), {desc}, NULL, {' | '.join(flags) or '0'}, 0, NULL, NULL }},"
        )
    by_name = sorted(range(len(fs)), key=lambda i: fs[i].name)
    ranges, prev = [], None
    for i, f in enumerate(fs):
        if prev is None or f.id != prev + 1:
            ranges.append(f"{{ {f.id}, {i} }}")
        prev = f.id
    ranges.append(f"{{ 0, {len(fs)} }}")
    return f"""static const ProtobufCFieldDescriptor {prefix}__field_descriptors[{len(fs)}] = {{
{chr(10).join(rows)}
}};
static const unsigned {prefix}__field_indices_by_name[] = {{ {", ".join(map(str, by_name))} }};
static const ProtobufCIntRange {prefix}__number_ranges[{len(ranges)}] = {{ {", ".join(ranges)} }};
"""


def random_fill(fs: list[Field]) -> str:
    lines = []
    for f in fs:
        if f.oneof:
            continue
        n, t = f.name, f.ptype
        if t == "message":
            if f.label == "REPEATED":
                lines += [
                    f"\tm->n_{n} = depth < 2 ? rnd() % 3 : 0;",
                    f"\tm->{n} = arena(m->n_{n} * sizeof(Cover *));",
                    f"\tfor (size_t i = 0; i < m->n_{n}; i++) {{ m->{n}[i] = arena(sizeof(Cover)); cover__random(m->{n}[i], depth + 1); }}",
                ]
            elif f.label == "REQUIRED":
                lines += [
                    f"\tm->{n} = NULL;",
                    # a CoverOpt (no required fields of its own), so NULL can pack as an empty one
                    f"\tif (depth < 2 && rnd() % 3 == 0) {{ m->{n} = arena(sizeof(Cover)); cover__random(m->{n}, depth + 1);"
                    f" m->{n}->base.descriptor = &cover_opt__descriptor; }}",
                ]
            else:
                lines += [
                    f"\tm->{n} = NULL;",
                    f"\tif (depth < 2 && rnd() % 4 == 0) {{ m->{n} = arena(sizeof(Cover)); cover__random(m->{n}, depth + 1); }}",
                ]
            continue
        value = SCALARS[t][1]
        if f.label == "REQUIRED":
            lines.append(f"\tm->{n} = {value};")
        elif f.label == "OPTIONAL":
            if t == "string":
                lines.append(f"\tm->{n} = rnd() & 1 ? {value} : NULL;")
            else:
                lines.append(f"\tif ((m->has_{n} = rnd() & 1)) m->{n} = {value};")
        elif f.label == "NONE":
            # proto3: zero values (and empty strings) are not written
            zero = {"string": 'arena_str("")', "bytes": "(ProtobufCBinaryData) { 0, NULL }"}.get(t, "0")
            lines.append(f"\tm->{n} = rnd() & 1 ? {value} : {zero};")
        else:
            lines += [
                # now and then long enough that a packed field's length prefix needs 2 bytes
                f"\tm->n_{n} = rnd() % 4 == 0 ? 0 : rnd() % 16 == 0 ? 100 + rnd() % 200 : rnd() % 6;",
                f"\tm->{n} = arena(m->n_{n} * sizeof(*m->{n}));",
                # repeated strings can't hold NULL
                f"\tfor (size_t i = 0; i < m->n_{n}; i++) m->{n}[i] = {value.replace('rv_string()', 'rv_string_set()')};",
            ]
    lines.append("\tswitch (rnd() % 5) {")
    for k, f in enumerate([f for f in fs if f.oneof]):
        lines.append(
            f"\tcase {k}: m->pick_case = COVER__PICK_{f.name.upper()}; m->{f.name} = {SCALARS[f.ptype][1]}; break;"
        )
    lines.append("\tdefault: m->pick_case = COVER__PICK__NOT_SET;")
    lines.append("\t}")
    return "\n".join(lines)


SUPPORT = r"""
static uint64_t rng = 0x243f6a8885a308d3u;
void cover__seed(uint64_t seed) { rng = seed | 1; }
static uint64_t rnd(void)
{
	rng ^= rng << 13;
	rng ^= rng >> 7;
	rng ^= rng << 17;
	return rng;
}

static unsigned char arena_mem[1 << 24];
static size_t arena_used;
void cover__arena_reset(void) { arena_used = 0; }
static void *arena(size_t n)
{
	void *p = &arena_mem[arena_used];
	arena_used += (n + 15) & ~(size_t) 15;
	if (arena_used > sizeof arena_mem) abort();
	return p;
}
static char *arena_str(const char *s)
{
	char *p = arena(strlen(s) + 1);
	strcpy(p, s);
	return p;
}

/* Edge cases half the time, otherwise a random value of random bit length. */
static uint64_t rv_bits(int bits)
{
	uint64_t top = bits == 64 ? ~(uint64_t) 0 : ((uint64_t) 1 << bits) - 1;
	uint64_t sign = (uint64_t) 1 << (bits - 1);
	switch (rnd() % 12) {
	case 0: return 0;
	case 1: return 1;
	case 2: return top;                      /* -1 */
	case 3: return sign;                     /* minimum */
	case 4: return sign - 1;                 /* maximum */
	case 5: return (uint64_t) 1 << (rnd() % bits);
	case 6: return ((uint64_t) 1 << (rnd() % bits)) - 1;
	case 7: return (top ^ (((uint64_t) 1 << (rnd() % bits)) - 1));  /* small negative */
	default: {
		int len = 1 + rnd() % bits;
		uint64_t v = rnd() & (len == 64 ? ~(uint64_t) 0 : ((uint64_t) 1 << len) - 1);
		/* sign-extend narrow values half the time, so negative int32s occur */
		if (bits == 32 && (rnd() & 1) && (v & sign)) v |= ~top;
		return v & top;
	}
	}
}
static float rv_float(void)
{
	static const float edge[] = { 0.0f, -0.0f, 1.0f, -1.5f, 3.4e38f, 1e-45f };
	if (rnd() & 1) return edge[rnd() % 6];
	uint32_t b = (uint32_t) rnd();
	float f;
	memcpy(&f, &b, 4);
	return f != f ? 0.25f : f;  /* no NaN: they don't compare equal */
}
static double rv_double(void)
{
	static const double edge[] = { 0.0, -0.0, 1.0, -1.5, 1.7e308, 5e-324 };
	if (rnd() & 1) return edge[rnd() % 6];
	uint64_t b = rnd();
	double d;
	memcpy(&d, &b, 8);
	return d != d ? 0.25 : d;
}
static Cover__Color rv_color(void)
{
	static const Cover__Color c[] = { COVER__COLOR__RED, COVER__COLOR__GREEN, COVER__COLOR__BLUE, COVER__COLOR__NEGATIVE };
	return c[rnd() % 4];
}
static char *rv_string(void)
{
	/* lengths around the 1- and 2-byte length-prefix boundary */
	static const size_t lens[] = { 0, 1, 7, 127, 128, 300 };
	if (rnd() % 8 == 0) return NULL;  /* packs as "" (or as absent when optional) */
	size_t n = lens[rnd() % 6];
	char *s = arena(n + 1);
	for (size_t i = 0; i < n; i++) s[i] = (char) ('a' + rnd() % 26);
	s[n] = 0;
	return s;
}
static char *rv_string_set(void)
{
	char *s;
	while (!(s = rv_string()))
		;
	return s;
}
static ProtobufCBinaryData rv_bytes(void)
{
	static const size_t lens[] = { 0, 1, 16, 127, 128, 1000 };
	ProtobufCBinaryData b = { lens[rnd() % 6], NULL };
	b.data = arena(b.len + 1);
	for (size_t i = 0; i < b.len; i++) b.data[i] = (uint8_t) rnd();
	return b;
}
"""


def source(fs: list[Field]) -> str:
    lite = [f for i, f in enumerate(fs) if in_lite(i, f)]
    # `must` is optional here, so an empty CoverOpt (what NULL packs as) is complete
    opt = [f if f.name != "must" else Field("must", "message", "OPTIONAL") for f in fs if f.label != "REQUIRED" or f.name == "must"]
    for f, g in zip(opt, [f for f in fs if f.label != "REQUIRED" or f.name == "must"]):
        f.id = g.id
    msg = lambda d, prefix, n, c: f"""const ProtobufCMessageDescriptor {d} = {{
	PROTOBUF_C__MESSAGE_DESCRIPTOR_MAGIC,
	"cover.{c}", "{c}", "{c}", "cover",
	sizeof(Cover),
	{n},
	{prefix}__field_descriptors,
	{prefix}__field_indices_by_name,
	sizeof({prefix}__number_ranges) / sizeof({prefix}__number_ranges[0]) - 1, {prefix}__number_ranges,
	(ProtobufCMessageInit) {prefix}__init,
	NULL, NULL, NULL
}};
"""
    return f"""/* Generated by gen_cover.py in the form protoc-c generates. */
#include <stddef.h>
#include <stdlib.h>
#include <string.h>

#include "cover.pb-c.h"

static const ProtobufCEnumValue cover__color__values[] = {{
	{{ "NEGATIVE", "COVER__COLOR__NEGATIVE", -3 }},
	{{ "RED", "COVER__COLOR__RED", 0 }},
	{{ "GREEN", "COVER__COLOR__GREEN", 1 }},
	{{ "BLUE", "COVER__COLOR__BLUE", 5 }},
}};
static const ProtobufCEnumValueIndex cover__color__by_name[] = {{
	{{ "BLUE", 3 }}, {{ "GREEN", 2 }}, {{ "NEGATIVE", 0 }}, {{ "RED", 1 }},
}};
static const ProtobufCIntRange cover__color__ranges[] = {{ {{ -3, 0 }}, {{ 0, 1 }}, {{ 5, 3 }}, {{ 0, 4 }} }};
const ProtobufCEnumDescriptor cover__color__descriptor = {{
	PROTOBUF_C__ENUM_DESCRIPTOR_MAGIC,
	"cover.Color", "Color", "Cover__Color", "cover",
	4, cover__color__values,
	4, cover__color__by_name,
	3, cover__color__ranges,
	NULL, NULL, NULL, NULL
}};

void cover__init(Cover *message)
{{
	memset(message, 0, sizeof *message);
	message->base.descriptor = &cover__descriptor;
}}

void cover_lite__init(Cover *message)
{{
	memset(message, 0, sizeof *message);
	message->base.descriptor = &cover_lite__descriptor;
}}

void cover_opt__init(Cover *message)
{{
	memset(message, 0, sizeof *message);
	message->base.descriptor = &cover_opt__descriptor;
}}

{descriptor_table(fs, "cover", "cover__descriptor")}
{msg("cover__descriptor", "cover", len(fs), "Cover")}
{descriptor_table(lite, "cover_lite", "cover_lite__descriptor")}
{msg("cover_lite__descriptor", "cover_lite", len(lite), "CoverLite")}
{descriptor_table(opt, "cover_opt", "cover__descriptor")}
{msg("cover_opt__descriptor", "cover_opt", len(opt), "CoverOpt")}
{SUPPORT}
void cover__random(Cover *m, int depth)
{{
	cover__init(m);
{random_fill(fs)}
}}
"""


if __name__ == "__main__":
    here = Path(__file__).parent
    fs = fields()
    (here / "cover.pb-c.h").write_text(header(fs))
    (here / "cover.pb-c.c").write_text(source(fs))
    print(f"{len(fs)} fields, {sum(in_lite(i, f) for i, f in enumerate(fs))} in CoverLite")
