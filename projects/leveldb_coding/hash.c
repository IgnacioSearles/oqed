/* LevelDB util/hash.cc and util/bloom.cc (google/leveldb bb74ef7), in C. */
#include "coding.h"

uint32_t Hash(const char *data, size_t n, uint32_t seed)
{
	// Similar to murmur hash
	const uint32_t m = 0xc6a4a793;
	const uint32_t r = 24;
	const char *limit = data + n;
	uint32_t h = seed ^ (n * m);

	// Pick up four bytes at a time
	while (limit - data >= 4) {
		uint32_t w = DecodeFixed32(data);
		data += 4;
		h += w;
		h *= m;
		h ^= (h >> 16);
	}

	// Pick up remaining bytes
	switch (limit - data) {
	case 3:
		h += (uint8_t) (data[2]) << 16;
		/* fallthrough */
	case 2:
		h += (uint8_t) (data[1]) << 8;
		/* fallthrough */
	case 1:
		h += (uint8_t) (data[0]);
		h *= m;
		h ^= (h >> r);
		break;
	}
	return h;
}

static uint32_t BloomHash(const Slice *key) { return Hash(key->data, key->size, 0xbc9f1d34); }

Bloom bloom_policy(int bits_per_key)
{
	Bloom p = {bits_per_key, 0};
	// We intentionally round down to reduce probing cost a little bit
	p.k = (size_t) (bits_per_key * 0.69); // 0.69 =~ ln(2)
	if (p.k < 1) p.k = 1;
	if (p.k > 30) p.k = 30;
	return p;
}

void CreateFilter(const Bloom *p, const Slice *keys, int n, Buf *dst)
{
	// Compute bloom filter size (in both bits and bytes)
	size_t bits = n * p->bits_per_key;

	// For small n, we can see a very high false positive rate.  Fix it
	// by enforcing a minimum bloom filter length.
	if (bits < 64) bits = 64;

	size_t bytes = (bits + 7) / 8;
	bits = bytes * 8;

	const size_t init_size = dst->size;
	buf_resize(dst, init_size + bytes);
	buf_push(dst, (char) p->k); // Remember # of probes in filter
	char *array = &dst->data[init_size];
	for (int i = 0; i < n; i++) {
		// Use double-hashing to generate a sequence of hash values.
		// See analysis in [Kirsch,Mitzenmacher 2006].
		uint32_t h = BloomHash(&keys[i]);
		const uint32_t delta = (h >> 17) | (h << 15); // Rotate right 17 bits
		for (size_t j = 0; j < p->k; j++) {
			const uint32_t bitpos = h % bits;
			array[bitpos / 8] |= (1 << (bitpos % 8));
			h += delta;
		}
	}
}

int KeyMayMatch(const Slice *key, const Slice *bloom_filter)
{
	const size_t len = bloom_filter->size;
	if (len < 2) return 0;

	const char *array = bloom_filter->data;
	const size_t bits = (len - 1) * 8;

	// Use the encoded k so that we can read filters generated by
	// bloom filters created using different parameters.
	const size_t k = array[len - 1];
	if (k > 30) {
		// Reserved for potentially new encodings for short bloom filters.
		// Consider it a match.
		return 1;
	}

	uint32_t h = BloomHash(key);
	const uint32_t delta = (h >> 17) | (h << 15); // Rotate right 17 bits
	for (size_t j = 0; j < k; j++) {
		const uint32_t bitpos = h % bits;
		if ((array[bitpos / 8] & (1 << (bitpos % 8))) == 0) return 0;
		h += delta;
	}
	return 1;
}
